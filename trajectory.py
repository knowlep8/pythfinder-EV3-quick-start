"""
Trajectory playback for a SPIKE Prime hub.

MicroPython port of the PythFinder builder, kept deliberately cheap: the
motor powers and target headings are precomputed on the PC, so the only math
that runs while following a path is the heading PID correction.

Two differences from the EV3 version, both forced by the hub:

  1. There is no filesystem, so a trajectory is no longer read from a .txt at
     runtime. Convert it on the PC first:

         python3 tools/txt_to_py.py Trajectory/TXT/mypath.txt

     then import the generated module and hand it to Trajectory().

  2. There is no threading module, so markers run *inline* on the follow loop
     rather than on their own thread. Keep marker functions short and
     non-blocking -- anything slow will stall the path being followed.
"""

from struct import unpack_from

from pybricks.parameters import Stop
from pybricks.tools import StopWatch

from constants import kD_head, kP_head
from math_ex import findShortestPath
from pid import PIDController


# Each state is 3 little-endian int16: left*100, right*100, heading*10.
_STATE_FORMAT = '<hhh'
_STATE_SIZE = 6


class Marker():
    """A function fired once, when the path reaches a given timestamp."""

    def __init__(self, time=None, fun=None):
        self.value = time
        self.fun = fun

    def do(self):
        if self.fun is None:
            print("\n\nexcuse me, what? \nprovide a method in the 'Marker' "
                  "object with the value '{0}'".format(self.value))
            return
        self.fun()


class _Values():
    """The four things read() wants, when they did not arrive as a module.

    Deliberately dull: it exists so fromValues() can go through exactly the
    same code as a generated module does.
    """

    def __init__(self, steps, markers, count, data):
        self.STEPS = steps
        self.MARKERS = markers
        self.COUNT = count
        self.DATA = data


class Trajectory():

    def __init__(self, data=None):
        self.head_controller = PIDController(kP=kP_head, kD=kD_head, kI=0)
        self.markers = None

        self.DATA = None
        self.STEPS = None
        self.COUNT = 0
        self.TRAJ_TIME = None

        if data is not None:
            self.read(data)

    @staticmethod
    def fromValues(steps, markers, count, data):
        """Build a trajectory from the four values, rather than from a module.

        The web planner writes a run as a single file that carries its own
        data *and* the code to drive it:

            STEPS = 6
            MARKERS = (1764, 7942)
            COUNT = 2607
            DATA = (b'...')

            def run(core):
                Trajectory.fromValues(STEPS, MARKERS, COUNT, DATA) ...

        which is tidier than a pair of files, and means runs.py needs only
        `import run_a`. A module cannot hand itself to Trajectory(module) on
        MicroPython -- there is no dependable way for it to refer to itself --
        so it hands over the values instead.

        Everything else is shared with read(), so the two ways of building a
        trajectory cannot drift apart.
        """
        return Trajectory(_Values(steps, markers, count, data))

    def read(self, data):
        """Take a module generated by tools/txt_to_py.py."""
        self.DATA = data.DATA
        self.STEPS = data.STEPS
        self.COUNT = data.COUNT
        self.TRAJ_TIME = self.COUNT * self.STEPS

        if self.markers is None:
            self.markers = []

        # Attach the timestamps to markers, creating any that .withMarkers()
        # has not already made.
        i = 0
        for each in data.MARKERS:
            if i < len(self.markers):
                self.markers[i].value = each
            else:
                self.markers.append(Marker(time=each))
            i += 1

        return self

    def withMarkers(self, fun):
        """Bind the action(s) the markers should perform, in path order."""
        if not isinstance(fun, tuple):
            if self.markers is None:
                self.markers = [Marker(fun=fun)]      # timestamp comes later
            else:
                self.markers[0].fun = fun
            return self

        if self.markers is None:
            self.markers = []

        i = 0
        for each in fun:
            if i < len(self.markers):
                self.markers[i].fun = each
            else:
                self.markers.append(Marker(fun=each))
            i += 1

        return self

    def follow(self, robot, telemetry=False):
        if not self.TRAJ_TIME:
            print('\n\nsomething is empty :(')
            print('it may be the trajectory')
            print("you'll never know...")
            return 0

        if telemetry:
            print('\n\nFOLLOWING TRAJECTORY...')

        if self.markers is None:
            self.markers = []

        self.marker_number = len(self.markers)
        self.marker_iterator = 0

        self.head_controller.reset()
        robot.zero()
        self.__realFollow(robot)
        robot.setDriveTo(Stop.BRAKE)
        robot.stopTaskMotors()

        # Anything scheduled for the final milliseconds, or past the end.
        while self.marker_iterator < self.marker_number:
            marker = self.markers[self.marker_iterator]

            if marker.value is not None and marker.value > self.TRAJ_TIME:
                print('\nThe marker number {0} exceeded the time limit of {1}ms by {2}ms'
                      .format(self.marker_iterator + 1, self.TRAJ_TIME,
                              marker.value - self.TRAJ_TIME))

            marker.do()
            self.marker_iterator += 1

        if telemetry:
            print('\n\nTRAJECTORY COMPLETED! ;)')

    def __realFollow(self, robot):
        marker = (None if self.marker_number == 0
                  else self.markers[self.marker_iterator])

        # Pulled out of the loop -- this runs a few thousand times per path.
        data = self.DATA
        steps = self.STEPS
        count = self.COUNT
        multiplier = robot.PID_multiplier
        controller = self.head_controller

        timer = StopWatch()
        time = 0

        while time < self.TRAJ_TIME:
            time = timer.time()

            index = int(time // steps)
            if index >= count:
                break

            LEFT, RIGHT, HEAD = unpack_from(_STATE_FORMAT, data,
                                            index * _STATE_SIZE)
            LEFT = LEFT / 100
            RIGHT = RIGHT / 100
            target_angle = HEAD / 10

            if marker is not None and time >= marker.value:
                marker.do()
                self.marker_iterator += 1
                marker = (None if self.marker_iterator >= self.marker_number
                          else self.markers[self.marker_iterator])

            if LEFT == 0 and RIGHT == 0:
                robot.setDriveTo(Stop.BRAKE)

            head_error = findShortestPath(robot.getHeading(), target_angle)
            correction = controller.calculate(head_error) * multiplier

            robot.setWheelPowers(LEFT - correction, RIGHT + correction)
